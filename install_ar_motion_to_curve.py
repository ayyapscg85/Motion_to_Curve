def _install_files():
    scripts_dir = cmds.internalVar(userScriptDir=True)
    script_path = os.path.join(scripts_dir, SCRIPT_FILENAME)
    icon_path = os.path.join(scripts_dir, ICON_FILENAME)

    with open(script_path, "w") as f:
        f.write(base64.b64decode(SCRIPT_B64).decode("utf-8"))

    with open(icon_path, "wb") as f:
        f.write(base64.b64decode(ICON_B64))

    return script_path, icon_path


def _install_shelf_button(icon_path):
    current_shelf = cmds.tabLayout("ShelfLayout", query=True, selectTab=True)

    # remove a previous copy of this button so re-running the installer
    # updates it in place instead of stacking up duplicates
    for btn in (cmds.shelfLayout(current_shelf, query=True, childArray=True) or []):
        try:
            if cmds.shelfButton(btn, query=True, exists=True) and \
                    cmds.shelfButton(btn, query=True, label=True) == SHELF_BUTTON_LABEL:
                cmds.deleteUI(btn)
        except Exception:
            pass

    command = (
        "import importlib\n"
        "import ar_motion_to_curve_ui\n"
        "importlib.reload(ar_motion_to_curve_ui)\n"
        "ar_motion_to_curve_ui.show_ui()\n"
    )

    cmds.shelfButton(
        parent=current_shelf,
        label=SHELF_BUTTON_LABEL,
        annotation="AR Motion to Curve - motion to curve tool",
        image=icon_path,
        image1=icon_path,
        command=command,
        sourceType="python",
    )
    return current_shelf


def onMayaDroppedPythonFile(*args, **kwargs):
    """Maya calls this automatically when the dropped .py file defines it."""
    script_path, icon_path = _install_files()
    shelf_name = _install_shelf_button(icon_path)

    cmds.confirmDialog(
        title="AR Motion to Curve",
        message=(
            "Installed successfully.\n\n"
            "Script installed to:\n%s\n\n"
            "A shelf button was added to '%s'."
        ) % (script_path, shelf_name),
        button=["OK"],
    )


if __name__ == "__main__":
    # allow running directly inside Maya's Script Editor too, not just drag/drop
    onMayaDroppedPythonFile()
